/**
 * Polymarket Builder Program — per-user DEPOSIT WALLET lane (2026-07-06).
 *
 * WHY: the CLOB rejects every maker that is not a registered deposit wallet.
 * Captured live: bare-EOA makers AND our relayer-deployed 1/1 Gnosis Safe
 * both bounce with "maker address not allowed, please use the deposit wallet
 * flow" (Safe attempt 2026-07-06, docs/probes/). The working lane is the one
 * the error names: a relayer-deployed UUPS deposit wallet
 * (DepositWalletFactory via @polymarket/builder-relayer-client) owned by the
 * user's Privy EOA. Orders go out signatureType=3 (POLY_1271) with
 * funderAddress = wallet; the EOA SIGNS + AUTHENTICATES (EOA-bound L2 creds),
 * clob-client-v2 stamps the order's `signer` field with the wallet (maker),
 * and the exchange validates the EOA signature via the wallet's EIP-1271 owner
 * check. Live-proven 2026-07-06 (France GTC `status:"live" success:true`, then
 * cancelled). The CLOB refuses to issue wallet-bound creds (`/auth/api-key`
 * POLY_ADDRESS=wallet → 401), so EOA creds are the only path — see the
 * identity block in pm-clob.ts.
 *
 * The Gnosis Safe machinery below is RETAINED: (a) rollback lane if the
 * deposit-wallet rollout regresses, (b) recovery path — live funds already
 * sit in at least one user Safe and `client.execute` is how they move out.
 *
 * Verified against docs/references/privy-safe-builder-example (official
 * Polymarket example) and the SDK dists pinned in this repo:
 *   - @polymarket/builder-relayer-client 0.0.10 — RelayClient accepts a viem
 *     WalletClient. We hand it one whose account is a custom viem account
 *     backed by Privy server signing: EIP-712 via signTypedDataWithPrivy,
 *     personal_sign via local hashMessage + raw secp256k1Sign (Privy's own
 *     signMessage would re-hash the SafeTx hash as UTF-8 text; the SDK's
 *     splitAndPackSig applies the Safe eth_sign v adjustment itself).
 *     signTransaction still throws loudly rather than guess.
 *   - Relayer auth = TWO independent header sets, both attached when present:
 *       1. POLY_BUILDER_* HMAC headers, generated by
 *          @polymarket/builder-signing-sdk BuilderConfig{localBuilderCreds}
 *          inside RelayClient.sendAuthedRequest (submit/transactions), and
 *       2. RELAYER_API_KEY + RELAYER_API_KEY_ADDRESS static headers from the
 *          builder settings page ("Relayer API keys", added 2026-07-05) —
 *          injected by wrapping the client's HttpClient.send.
 *   - The Safe address is CREATE2-deterministic:
 *     deriveSafe(eoa, SafeFactory) with the factory read from the relayer
 *     client's own getContractConfig(137) — never hardcoded.
 *   - Approvals execute FROM the Safe via relayer.execute() (gasless, paid
 *     by the Builder Program): ERC-20 approve(max) on BOTH the v2 SDK
 *     collateral (pUSD proxy 0xC011…2DFB) and legacy USDC.e for every
 *     exchange generation + negRiskAdapter + the CTF itself, plus CTF
 *     setApprovalForAll for the exchange generations + adapter. The
 *     operator set derives from @polymarket/clob-client-v2
 *     getContractConfig(137) — the EXACT config order signing uses — so
 *     approvals can never drift from orders (same rule as pm-approvals.ts).
 *
 * Money-safety invariants:
 *   - Every mutating relayer step polls to STATE_MINED/STATE_CONFIRMED and
 *     THROWS on STATE_FAILED or timeout — no fire-and-forget.
 *   - The order path only engages the wallet funder after
 *     `getDepositWalletStatus` verifies deployed + fully approved
 *     (`getBuilderLaneFunder`), and only when PM_BUILDER_LANE is explicitly
 *     enabled.
 *   - `fundSafeFromEoa` fails CLOSED on demo/failed executor results — a
 *     "funding" that didn't verifiably move money never reports success.
 */

