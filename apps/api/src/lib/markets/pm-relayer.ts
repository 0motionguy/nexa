export interface PmOperatorSets {
  /** v2 SDK collateral — the pUSD proxy the CLOB settles in. */
  collateral: `0x${string}`;
  /** ERC-20s the Safe approves: [pUSD, USDC.e]. */
  erc20Tokens: `0x${string}`[];
  /** Spenders for every ERC-20 approval (exchange gens + adapter + CTF). */
  erc20Spenders: `0x${string}`[];
  ctf: `0x${string}`;
  /** ERC-1155 operators (exchange gens + adapter). */
  ctfOperators: `0x${string}`[];
}

function uniqAddresses(list: Array<string | undefined>): `0x${string}`[] {
  const seen = new Set<string>();
  const out: `0x${string}`[] = [];
  for (const raw of list) {
    if (!raw) continue;
    const a = getAddress(raw);
    if (seen.has(a.toLowerCase())) continue;
    seen.add(a.toLowerCase());
    out.push(a);
  }
  return out;
}

/**
 * Pure derivation from a v2-style contract config — exported for tests so
 * the deposit-wallet operator set is pinned.
 *
 * VERSION-2 SET ONLY (2026-07-06): the Polymarket relayer's deposit-wallet
 * call filter allow-lists ONLY the current-generation operators. Live-probed:
 * approving the legacy V1 `exchange` (0x4bFb…8982E) is rejected "call blocked:
 * … not in the allowed list", while `exchangeV2` + `negRiskExchangeV2` +
 * `negRiskAdapter` are accepted and mine. Live CLOB `/version` = 2, so orders
 * settle through exactly these. The V1 exchanges and (untested) exchangeV3 are
 * excluded — including a blocked spender fails the whole atomic approval batch,
 * AND would leave `getDepositWalletStatus.ready` permanently false. Add
 * exchangeV3 here when CLOB `/version` advances to 3.
 */
export function operatorSetsFromConfig(cfg: Record<string, string>): PmOperatorSets {
  // Fail loudly if the SDK's contract-config shape ever drifts — deploying
  // approvals against a partial operator set would strand user funds.
  const collateral = cfg.collateral;
  const ctf = cfg.conditionalTokens;
  if (!collateral || !ctf) throw new Error('pm_relayer_config_missing_core');
  const operators = uniqAddresses([
    cfg.exchangeV2,
    cfg.negRiskExchangeV2,
    cfg.negRiskAdapter,
  ]);
  return {
    collateral: getAddress(collateral),
    erc20Tokens: uniqAddresses([collateral, USDCE_POLYGON]),
    erc20Spenders: uniqAddresses([...operators, ctf]),
    ctf: getAddress(ctf),
    ctfOperators: operators,
  };
}

let _sets: PmOperatorSets | null = null;
export async function pmOperatorSets(): Promise<PmOperatorSets> {
  if (_sets) return _sets;
  const { getContractConfig } = await import('@polymarket/clob-client-v2');
  _sets = operatorSetsFromConfig(getContractConfig(POLY_CHAIN_ID) as unknown as Record<string, string>);
  return _sets;
}

