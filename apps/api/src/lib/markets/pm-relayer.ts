export interface PmSafeStatus {
  safe: `0x${string}`;
  deployed: boolean;
  missingErc20: Array<{ token: `0x${string}`; spender: `0x${string}` }>;
  missingCtf: `0x${string}`[];
  /** true ⇔ deployed and zero missing approvals — orders may use the Safe funder. */
  ready: boolean;
}

interface OwnerApprovalStatus {
  deployed: boolean;
  missingErc20: Array<{ token: `0x${string}`; spender: `0x${string}` }>;
  missingCtf: `0x${string}`[];
  /** true ⇔ deployed and zero missing approvals — orders may use this funder. */
  ready: boolean;
}

/**
 * Deployment + approval posture for any maker candidate (Safe or deposit
 * wallet): bytecode present, and `owner`-side allowance/isApprovedForAll for
 * the full operator set.
 */
async function ownerApprovalStatus(owner: `0x${string}`): Promise<OwnerApprovalStatus> {
  const sets = await pmOperatorSets();
  const erc20Pairs = sets.erc20Tokens.flatMap((token) =>
    sets.erc20Spenders.map((spender) => ({ token, spender })),
  );
  const pc = publicClient();
  const code = await pc.getCode({ address: owner }).catch(() => undefined);
  const deployed = code !== undefined && code !== '0x';
  if (!deployed) {
    // Undeployed maker trivially has no approvals — skip 20 pointless reads.
    return { deployed: false, missingErc20: erc20Pairs, missingCtf: [...sets.ctfOperators], ready: false };
  }
  const contracts = [
    ...erc20Pairs.map(({ token, spender }) => ({
      address: token,
      abi: erc20Abi,
      functionName: 'allowance' as const,
      args: [owner, spender] as const,
    })),
    ...sets.ctfOperators.map((operator) => ({
      address: sets.ctf,
      abi: CTF_ABI,
      functionName: 'isApprovedForAll' as const,
      args: [owner, operator] as const,
    })),
  ];
  // allowFailure — a failed read counts as MISSING (conservative: worst case
  // we re-submit an idempotent approval, never skip a required one).
  const results = await pc.multicall({ contracts: contracts as never, allowFailure: true });
  const missingErc20: Array<{ token: `0x${string}`; spender: `0x${string}` }> = [];
  const missingCtf: `0x${string}`[] = [];
  erc20Pairs.forEach((pair, i) => {
    const r = results[i] as { status: string; result?: unknown } | undefined;
    const ok = r?.status === 'success' && typeof r.result === 'bigint' && r.result >= MIN_ALLOWANCE;
    if (!ok) missingErc20.push(pair);
  });
  sets.ctfOperators.forEach((operator, j) => {
    const r = results[erc20Pairs.length + j] as { status: string; result?: unknown } | undefined;
    const ok = r?.status === 'success' && r.result === true;
    if (!ok) missingCtf.push(operator);
  });
  return {
    deployed,
    missingErc20,
    missingCtf,
    ready: missingErc20.length === 0 && missingCtf.length === 0,
  };
}

export async function getSafeStatus(eoa: `0x${string}`): Promise<PmSafeStatus> {
  const safe = await deriveUserSafe(eoa);
  return { safe, ...(await ownerApprovalStatus(safe)) };
}

