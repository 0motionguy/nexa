/**
 * Live pUSD collateral balance of a builder-lane deposit wallet, in USD.
 *
 * The order route pre-checks this so an underfunded order fails fast with an
 * actionable `insufficient_prediction_balance` + shortfall payload instead of
 * the CLOB's raw "not enough balance / allowance" 422 (live-tested
 * 2026-07-06: balance 475020 atoms vs order amount 622560). Reads the same
 * operator-set collateral the CLOB settles against.
 */
export async function getDepositWalletCollateralUsd(
  wallet: `0x${string}`,
): Promise<number> {
  const sets = await pmOperatorSets();
  const balance = (await publicClient().readContract({
    address: sets.collateral,
    abi: erc20Abi,
    functionName: 'balanceOf',
    args: [wallet],
  })) as bigint;
  return Number(balance) / 1e6;
}
