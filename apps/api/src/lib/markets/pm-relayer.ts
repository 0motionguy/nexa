/**
 * Per-EOA deposit wallet address cache. Unlike the Safe's pure CREATE2
 * derivation, deposit-wallet derivation probes the factory's beacon through
 * a signer-bound RelayClient — cache the stable result so lane resolution
 * stays one multicall like the Safe path was.
 */
const _depositWallets = new Map<string, `0x${string}`>();

/** Relayer-derived (UUPS/beacon) per-user deposit wallet address. */
export async function deriveUserDepositWallet(
  walletId: string,
  eoa: `0x${string}`,
): Promise<`0x${string}`> {
  const key = getAddress(eoa);
  const hit = _depositWallets.get(key);
  if (hit) return hit;
  const client = await relayClientFor(walletId, eoa);
  const wallet = getAddress(await client.deriveDepositWalletAddress());
  _depositWallets.set(key, wallet);
  return wallet;
}

export interface PmWalletStatus extends OwnerApprovalStatus {
  wallet: `0x${string}`;
}

export async function getDepositWalletStatus(
  walletId: string,
  eoa: `0x${string}`,
): Promise<PmWalletStatus> {
  const wallet = await deriveUserDepositWallet(walletId, eoa);
  return { wallet, ...(await ownerApprovalStatus(wallet)) };
}

/* ------------------------------------------------------------------ *
 * Approval transaction planning (pure — unit-tested)                  *
 * ------------------------------------------------------------------ */

export function buildApprovalTxs(
  missingErc20: Array<{ token: `0x${string}`; spender: `0x${string}` }>,
  missingCtf: `0x${string}`[],
  ctf: `0x${string}`,
): SafeTransaction[] {
  const txns: SafeTransaction[] = [];
  for (const { token, spender } of missingErc20) {
    txns.push({
      to: token,
      // OperationType.Call — numeric enum, type-only import keeps runtime lean.
      operation: 0 as OperationType,
      data: encodeFunctionData({ abi: erc20Abi, functionName: 'approve', args: [spender, maxUint256] }),
      value: '0',
    });
  }
  for (const operator of missingCtf) {
    txns.push({
      to: ctf,
      operation: 0 as OperationType,
      data: encodeFunctionData({ abi: CTF_ABI, functionName: 'setApprovalForAll', args: [operator, true] }),
      value: '0',
    });
  }
  return txns;
}

/**
 * Safe txns → deposit-wallet batch calls. Deposit wallets execute plain
 * CALLs only (no delegatecall), which is exactly what buildApprovalTxs
 * emits — the mapping is pure field renames, unit-tested.
 */
export function depositCallsFromTxs(txns: SafeTransaction[]): DepositWalletCall[] {
  return txns.map((t) => ({ target: t.to, value: t.value ?? '0', data: t.data }));
}

export function chunkTxns<T>(items: T[], size: number): T[][] {
  if (size <= 0) throw new Error('pm_relayer_invalid_chunk_size');
  const out: T[][] = [];
  for (let i = 0; i < items.length; i += size) out.push(items.slice(i, i + size));
  return out;
}

