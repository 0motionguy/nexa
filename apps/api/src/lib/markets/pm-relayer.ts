function relayerKeyHeaders(): Record<string, string> | null {
  const key = env.POLYMARKET_RELAYER_API_KEY;
  const address = env.POLYMARKET_RELAYER_API_KEY_ADDRESS;
  if (!key || !address) return null;
  return { RELAYER_API_KEY: key, RELAYER_API_KEY_ADDRESS: address };
}

/**
 * viem WalletClient whose account signs EIP-712 and EIP-191 via the Privy
 * server wallet. Exported for unit tests (byte-identity vs a local key).
 */
export function privySafeWalletClient(walletId: string, address: `0x${string}`): WalletClient {
  const account = toAccount({
    address: getAddress(address),
    async signMessage({ message }): Promise<`0x${string}`> {
      // The relayer SDK personal_signs the SafeTx struct hash as { raw }
      // bytes. Privy's own signMessage would re-interpret the 0x hash as
      // UTF-8 text (see signHashWithPrivy docs), so compose the EIP-191
      // digest locally and raw-sign it — byte-identical to a local
      // private-key account. The SDK's splitAndPackSig applies the Safe
      // eth_sign v adjustment (27/28→+4, 0/1→+31) itself, so we return a
      // STANDARD 65-byte signature untouched.
      const sig = await signHashWithPrivy(walletId, hashMessage(message));
      if (!sig) throw new Error('pm_relayer_signature_unavailable');
      return sig as `0x${string}`;
    },
    async signTransaction(): Promise<`0x${string}`> {
      throw new Error('pm_relayer_sign_transaction_unsupported');
    },
    async signTypedData(typedData): Promise<`0x${string}`> {
      const sig = await signTypedDataWithPrivy(walletId, typedData as never);
      if (!sig) throw new Error('pm_relayer_signature_unavailable');
      return sig as `0x${string}`;
    },
  });
  return createWalletClient({ account, chain: polygon, transport: http(rpcUrl()) });
}

interface RelayerHttpOptions {
  headers?: Record<string, unknown>;
  data?: unknown;
  params?: Record<string, unknown>;
}

export interface RelayerHttpish {
  httpClient: {
    send: (endpoint: string, method: string, options?: RelayerHttpOptions) => Promise<unknown>;
  };
}

/**
 * Inject the builder-settings "Relayer API key" header pair
 * (RELAYER_API_KEY / RELAYER_API_KEY_ADDRESS) on EVERY relayer request by
 * wrapping HttpClient.send. Exported for tests.
 */
export function attachRelayerKeyHeaders(client: RelayerHttpish, headers: Record<string, string> | null): void {
  if (!headers) return;
  const httpc = client.httpClient;
  const orig = httpc.send.bind(httpc);
  httpc.send = (endpoint, method, options) =>
    orig(endpoint, method, {
      ...(options ?? {}),
      headers: { ...headers, ...(options?.headers ?? {}) },
    });
}

export async function relayClientFor(walletId: string, eoa: `0x${string}`): Promise<RelayClient> {
  const hmac = builderHmacCreds();
  const keyHeaders = relayerKeyHeaders();
  if (!hmac && !keyHeaders) throw new Error('pm_relayer_auth_missing');
  const [{ RelayClient: RelayClientCtor, RelayerTxType }, sdk] = await Promise.all([
    import('@polymarket/builder-relayer-client'),
    import('@polymarket/builder-signing-sdk'),
  ]);
  const builderConfig = hmac ? new sdk.BuilderConfig({ localBuilderCreds: hmac }) : undefined;
  const client = new RelayClientCtor(
    relayerUrl(),
    POLY_CHAIN_ID,
    privySafeWalletClient(walletId, eoa),
    // relayer-client 0.0.10 types this param against its own NESTED
    // builder-signing-sdk 0.0.8; our direct dep is 1.0.0. Constructor and
    // method surfaces are identical (both d.ts verified 2026-07-05) and the
    // client only duck-calls generateBuilderHeaders()/isValid() — `never`
    // keeps the compile independent of which copy TS resolves.
    builderConfig as never,
    RelayerTxType.SAFE,
  );
  attachRelayerKeyHeaders(client as unknown as RelayerHttpish, keyHeaders);
  return client;
}

/* ------------------------------------------------------------------ *
 * Safe lifecycle: deploy + approvals (all gasless via relayer)        *
 * ------------------------------------------------------------------ */

async function awaitRelayerTx(
  client: RelayClient,
  resp: RelayerTransactionResponse,
  label: string,
): Promise<RelayerTransaction> {
  venueBreadcrumb('polymarket-relayer', `${label}.submitted`, {
    txId: resp.transactionID,
    state: resp.state,
  });
  const txn = await client.pollUntilState(resp.transactionID, RELAYER_OK_STATES, RELAYER_FAIL_STATE, 60, 3000);
  if (!txn) {
    venueBreadcrumb('polymarket-relayer', `${label}.failed`, { txId: resp.transactionID }, 'error');
    throw new Error(`pm_relayer_${label}_failed`);
  }
  venueBreadcrumb('polymarket-relayer', `${label}.mined`, {
    txId: resp.transactionID,
    hash: txn.transactionHash,
    state: txn.state,
  });
  return txn;
}

export interface EnsureSafeResult {
  safe: `0x${string}`;
  deployedNow: boolean;
  approvalsSubmitted: number;
  status: PmSafeStatus;
}

/**
 * Idempotently bring the user's Safe to trade-ready: deploy if missing, then
 * submit every missing approval FROM the Safe. Re-runnable; throws on any
 * non-mined relayer transaction. No user funds move here — deploy and
 * approvals are relayer-paid.
 */
export async function ensureBuilderSafe(walletId: string, eoa: `0x${string}`): Promise<EnsureSafeResult> {
  if (!walletId) throw new Error('pm_relayer_wallet_missing');
  let status = await getSafeStatus(eoa);
  const client = await relayClientFor(walletId, eoa);
  let deployedNow = false;

  if (!status.deployed) {
    try {
      const resp = await client.deploy();
      await awaitRelayerTx(client, resp, 'safe_deploy');
      deployedNow = true;
    } catch (e) {
      // Race-safe: a parallel setup (or the relayer's own view) may have
      // deployed it between our RPC read and the submit — treat as deployed.
      const msg = e instanceof Error ? e.message : String(e);
      if (!/deployed/i.test(msg)) throw e;
      log.info({ eoa, safe: status.safe }, 'pm-relayer: safe already deployed (race)');
    }
    status = await getSafeStatus(eoa);
    if (!status.deployed) throw new Error('pm_relayer_safe_not_deployed');
  }

  const sets = await pmOperatorSets();
  const txns = buildApprovalTxs(status.missingErc20, status.missingCtf, sets.ctf);
  let approvalsSubmitted = 0;
  for (const batch of chunkTxns(txns, APPROVAL_CHUNK_SIZE)) {
    // The relayer's own deployed-view can lag the chain by a few seconds
    // right after deploy — retry the NOT_DEPLOYED rejection briefly.
    let attempt = 0;
    for (;;) {
      try {
        const resp = await client.execute(batch, 'NEXA builder-lane approvals');
        await awaitRelayerTx(client, resp, 'safe_approvals');
        break;
      } catch (e) {
        const msg = e instanceof Error ? e.message : String(e);
        attempt += 1;
        if (attempt >= 4 || !/not deployed/i.test(msg)) throw e;
        await new Promise((r) => setTimeout(r, 3000));
      }
    }
    approvalsSubmitted += batch.length;
  }

  status = await getSafeStatus(eoa);
  if (!status.ready) throw new Error('pm_relayer_approvals_incomplete');
  laneCache.delete(getAddress(eoa));
  return { safe: status.safe, deployedNow, approvalsSubmitted, status };
}

export interface EnsureWalletResult {
  wallet: `0x${string}`;
  deployedNow: boolean;
  approvalsSubmitted: number;
  status: PmWalletStatus;
}

/**
 * Idempotently bring the user's DEPOSIT WALLET to trade-ready: deploy if
 * missing, then execute every missing approval FROM the wallet as
 * relayer-paid EIP-712 batches. Re-runnable; throws on any non-mined relayer
 * transaction. No user funds move here.
 */
export async function ensureBuilderDepositWallet(
  walletId: string,
  eoa: `0x${string}`,
): Promise<EnsureWalletResult> {
  if (!walletId) throw new Error('pm_relayer_wallet_missing');
  const client = await relayClientFor(walletId, eoa);
  const wallet = await deriveUserDepositWallet(walletId, eoa);
  let status = await getDepositWalletStatus(walletId, eoa);
  let deployedNow = false;

  if (!status.deployed) {
    try {
      const resp = await client.deployDepositWallet();
      await awaitRelayerTx(client, resp, 'wallet_deploy');
      deployedNow = true;
    } catch (e) {
      // Race-safe: a parallel setup (or the relayer's own view) may have
      // deployed it between our RPC read and the submit — treat as deployed.
      const msg = e instanceof Error ? e.message : String(e);
      if (!/deployed|exists/i.test(msg)) throw e;
      log.info({ eoa, wallet }, 'pm-relayer: deposit wallet already deployed (race)');
    }
    status = await getDepositWalletStatus(walletId, eoa);
    if (!status.deployed) throw new Error('pm_relayer_wallet_not_deployed');
  }

  const sets = await pmOperatorSets();
  const calls = depositCallsFromTxs(buildApprovalTxs(status.missingErc20, status.missingCtf, sets.ctf));
  let approvalsSubmitted = 0;
  for (const batch of chunkTxns(calls, APPROVAL_CHUNK_SIZE)) {
    // The relayer's own deployed-view can lag the chain by a few seconds
    // right after deploy — retry the NOT_DEPLOYED rejection briefly.
    let attempt = 0;
    for (;;) {
      try {
        // Fresh deadline per attempt — the batch signature must still be
        // in the future when the relayer finally executes it.
        const deadline = `${Math.floor(Date.now() / 1000) + 900}`;
        const resp = await client.executeDepositWalletBatch(batch, wallet, deadline);
        await awaitRelayerTx(client, resp, 'wallet_approvals');
        break;
      } catch (e) {
        const msg = e instanceof Error ? e.message : String(e);
        attempt += 1;
        if (attempt >= 4 || !/not deployed/i.test(msg)) throw e;
        await new Promise((r) => setTimeout(r, 3000));
      }
    }
    approvalsSubmitted += batch.length;
  }

  status = await getDepositWalletStatus(walletId, eoa);
  if (!status.ready) throw new Error('pm_relayer_approvals_incomplete');
  laneCache.delete(getAddress(eoa));
  return { wallet, deployedNow, approvalsSubmitted, status };
}

/* ------------------------------------------------------------------ *
 * Order-lane resolution                                               *
 * ------------------------------------------------------------------ */

export function pmBuilderLaneEnabled(): boolean {
  return env.PM_BUILDER_LANE === '1' || env.PM_BUILDER_LANE === 'true';
}

const laneCache = new Map<string, { v: ClobLane | null; exp: number }>();
const LANE_READY_TTL_MS = 300_000;
const LANE_RETRY_TTL_MS = 15_000;

/**
 * Resolve the deposit-wallet funder for a user's CLOB orders. Returns null
 * unless the lane is enabled AND the wallet is verified deployed + fully
 * approved — the order path falls back to the legacy lanes on null, never
 * half-engages. Takes the Privy walletId because deposit-wallet derivation
 * needs a signer-bound RelayClient (beacon probe).
 */
export async function getBuilderLaneFunder(
  walletId: string,
  eoa: `0x${string}`,
): Promise<ClobLane | null> {
  if (!pmBuilderLaneEnabled()) return null;
  if (!walletId) return null;
  const key = getAddress(eoa);
  const hit = laneCache.get(key);
  if (hit && hit.exp > Date.now()) return hit.v;
  let lane: ClobLane | null = null;
  try {
    const status = await getDepositWalletStatus(walletId, eoa);
    if (status.ready) {
      lane = {
        signatureType: SIGNATURE_TYPE_POLY_1271,
        funderAddress: status.wallet,
        ...(env.POLYMARKET_BUILDER_CODE ? { builderCode: env.POLYMARKET_BUILDER_CODE } : {}),
      };
    }
  } catch (e) {
    log.warn(
      { err: e instanceof Error ? e.message : String(e), eoa },
      'pm-relayer: lane status check failed — falling back to legacy lanes',
    );
    lane = null;
  }
  laneCache.set(key, { v: lane, exp: Date.now() + (lane ? LANE_READY_TTL_MS : LANE_RETRY_TTL_MS) });
  return lane;
}

export function _resetPmRelayerCachesForTests(): void {
  _publicClient = null;
  _sets = null;
  _safeFactory = null;
  _depositWallets.clear();
  laneCache.clear();
}

