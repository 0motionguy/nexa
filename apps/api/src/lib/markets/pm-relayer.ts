/**
 * Move ERC-20 collateral from the user's EOA into their Safe via the
 * existing EIP-7702 sponsored executor. Fails CLOSED on demo/failed results.
 */
export async function fundSafeFromEoa(
  userId: string,
  eoa: `0x${string}`,
  token: `0x${string}`,
  atoms: bigint,
): Promise<{ safe: `0x${string}`; txHash: string; sponsored: boolean }> {
  if (atoms <= 0n) throw new Error('pm_safe_fund_invalid_amount');
  const safe = await deriveUserSafe(eoa);
  const res = await executor.sendCalls(
    userId,
    [
      {
        to: token,
        data: encodeFunctionData({ abi: erc20Abi, functionName: 'transfer', args: [safe, atoms] }),
      },
    ],
    {
      chainId: POLY_CHAIN_ID,
      // Deterministic key: a queue/HTTP retry of the SAME funding intent
      // dedupes instead of double-spending.
      idempotencyKey: `pm-safe-fund:${eoa.toLowerCase()}:${token.toLowerCase()}:${atoms}`,
    },
  );
  if (res.demo || res.failed || !res.txHash || res.txHash.startsWith('0xdemo')) {
    throw new Error(`pm_safe_fund_not_live:${res.failureCode ?? (res.demo ? 'demo' : 'unknown')}`);
  }
  venueBreadcrumb('polymarket-relayer', 'safe_fund.submitted', {
    safe,
    token,
    atoms: atoms.toString(),
    txHash: res.txHash,
  });
  return { safe, txHash: res.txHash, sponsored: res.sponsored };
}

/**
 * Resolve how many collateral atoms a Safe-funding request should move.
 *
 * Default (no `requestedUsd`) sweeps the FULL EOA balance — the deposit lane
 * intentionally leaves nothing behind, mirroring the wrap flow that produced
 * the pUSD in the first place. An explicit amount converts at 6 decimals and
 * must fit inside the live balance: we fail closed here rather than let the
 * relayer submit an ERC-20 transfer that reverts on-chain.
 */
export function resolveFundAtoms(balance: bigint, requestedUsd?: number): bigint {
  const atoms = requestedUsd === undefined ? balance : BigInt(Math.round(requestedUsd * 1e6));
  if (atoms <= 0n) throw new Error('pm_safe_fund_invalid_amount');
  if (atoms > balance) throw new Error('pm_safe_fund_insufficient_balance');
  return atoms;
}

/**
 * Fund the user's builder-lane Safe with pUSD collateral from their EOA.
 *
 * Reads the live collateral balance (same operator-set source the CLOB signs
 * against), resolves the amount via {@link resolveFundAtoms}, and submits ONE
 * sponsored transfer through {@link fundSafeFromEoa}. Composes existing
 * fail-closed pieces so the HTTP route stays a thin adapter.
 */
export async function fundBuilderSafe(
  userId: string,
  eoa: `0x${string}`,
  requestedUsd?: number,
): Promise<{
  safe: `0x${string}`;
  txHash: string;
  sponsored: boolean;
  atoms: bigint;
  token: `0x${string}`;
}> {
  const sets = await pmOperatorSets();
  const balance = (await publicClient().readContract({
    address: sets.collateral,
    abi: erc20Abi,
    functionName: 'balanceOf',
    args: [eoa],
  })) as bigint;
  const atoms = resolveFundAtoms(balance, requestedUsd);
  const funded = await fundSafeFromEoa(userId, eoa, sets.collateral, atoms);
  return { ...funded, atoms, token: sets.collateral };
}

