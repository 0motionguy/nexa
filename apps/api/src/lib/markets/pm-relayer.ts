/**
 * Legacy bridged USDC.e — approved alongside pUSD so the Safe stays
 * compatible with both collateral generations (Polymarket's own UI grants
 * the same superset; approvals are gasless via the relayer).
 */
const USDCE_POLYGON = '0x2791Bca1f2de4661ED88A30C99A7a9449Aa84174' as `0x${string}`;

const CTF_ABI = parseAbi([
  'function isApprovedForAll(address owner, address operator) view returns (bool)',
  'function setApprovalForAll(address operator, bool approved)',
]);

/** ERC-20 allowances below half of max count as "needs approval" (mirrors pm-approvals.ts). */
const MIN_ALLOWANCE = maxUint256 / 2n;

/** Relayer batches are chunked so a Safe multisend never grows unbounded. */
const APPROVAL_CHUNK_SIZE = 12;

const RELAYER_OK_STATES = ['STATE_MINED', 'STATE_CONFIRMED'];
const RELAYER_FAIL_STATE = 'STATE_FAILED';

function relayerUrl(): string {
  return env.PM_RELAYER_URL && env.PM_RELAYER_URL.length > 0 ? env.PM_RELAYER_URL : RELAYER_URL_DEFAULT;
}

function rpcUrl(): string {
  return env.POLYGON_RPC_URL && env.POLYGON_RPC_URL.length > 0
    ? env.POLYGON_RPC_URL
    : 'https://polygon-rpc.com';
}

