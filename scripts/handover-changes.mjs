#!/usr/bin/env node
/**
 * handover-changes — generate the "what changed" inventory for a handover
 * doc from authoritative Git state, not memory.
 *
 * Why this exists
 * ---------------
 * Sprint 18's handover (HANDOVER-2026-06-22-SPRINT-18.md) claimed
 * "Working tree only — NOT committed" while a recent commit had already
 * landed most of the change set. Hand-writing inventory tables from
 * memory drifts faster than the repo. This script regenerates the
 * file-change table + per-commit list + dirty tree + untracked files
 * from `git` directly. Narrative decisions stay human-written; the
 * inventory must be generated.
 *
 * Usage
 * -----
 *   node scripts/handover-changes.mjs <base-ref> <head-ref>
 *
 * Example
 * -------
 *   node scripts/handover-changes.mjs 13f29d1 HEAD
 *
 * Output is markdown on stdout. Pipe to a file or paste into the
 * handover doc's "What changed" section.
 *
 * Safety
 * ------
 * Refs are validated against `git rev-parse --verify` BEFORE any other
 * git invocation. Arguments are passed as argv arrays to `spawnSync`,
 * never as a shell-concatenated string, so a ref like
 * `; rm -rf /` would fail validation, not get executed.
 */

import { spawnSync } from 'node:child_process';
import { argv, exit } from 'node:process';

/** Run git with arg-array; throw on non-zero. Returns trimmed stdout. */
function git(args, opts = {}) {
  const res = spawnSync('git', args, {
    stdio: ['ignore', 'pipe', 'pipe'],
    encoding: 'utf8',
    shell: false,
    ...opts,
  });
  if (res.status !== 0) {
    const err = new Error(
      `git ${args.join(' ')} failed (exit ${res.status ?? 'null'}): ${res.stderr?.trim() ?? ''}`,
    );
    err.exitCode = res.status ?? 1;
    throw err;
  }
  return (res.stdout ?? '').trim();
}

/** Returns the 40-char SHA for a ref, or throws. */
function resolveRef(ref) {
  return git(['rev-parse', '--verify', `${ref}^{commit}`]);
}

function usage() {
  console.error('Usage: handover-changes <base-ref> <head-ref>');
  console.error('Example: handover-changes 13f29d1 HEAD');
  exit(2);
}

const [baseRefArg, headRefArg] = argv.slice(2);
if (!baseRefArg || !headRefArg) usage();

// Validate before doing anything else. Bad refs fail loud.
let baseSha;
let headSha;
try {
  baseSha = resolveRef(baseRefArg);
  headSha = resolveRef(headRefArg);
} catch (e) {
  console.error(`[handover-changes] invalid ref: ${e.message}`);
  exit(2);
}

const range = `${baseSha}..${headSha}`;

// --- Section 1: commit list -------------------------------------------------
const commits = git(['log', '--oneline', '--no-decorate', range]).split('\n').filter(Boolean);
const commitCount = commits.length;

// --- Section 2: name-status (renames, deletes, adds, modifications) ---------
const nameStatus = git(['diff', '--name-status', range]).split('\n').filter(Boolean);

// --- Section 3: diff stat ---------------------------------------------------
const diffStat = git(['diff', '--stat', range]);

// --- Section 4: current dirty worktree --------------------------------------
const dirty = git(['status', '--porcelain=v2']).split('\n').filter(Boolean);
const dirtyTracked = dirty.filter((line) => line.startsWith('1 ') || line.startsWith('2 '));
const untracked = dirty.filter((line) => line.startsWith('? '));

// --- Render ------------------------------------------------------------------
function fence(lang, body) {
  return body && body.trim() ? '```' + lang + '\n' + body.trim() + '\n```' : '_(none)_';
}

const generatedAt = new Date().toISOString();
const header = `<!--
Auto-generated by scripts/handover-changes.mjs. Re-run to refresh; do
not hand-edit the inventory below. Narrative decisions go above/below
this block, not inside it.
-->`;

const lines = [];
lines.push(header);
lines.push('');
lines.push(`## What changed: \`${baseRefArg}..${headRefArg}\``);
lines.push('');
lines.push(`- Base: \`${baseSha}\` (\`${baseRefArg}\`)`);
lines.push(`- Head: \`${headSha}\` (\`${headRefArg}\`)`);
lines.push(`- Generated: ${generatedAt}`);
lines.push(`- Commits in range: **${commitCount}**`);
lines.push('');

lines.push('### Commits');
lines.push(fence('text', commits.join('\n')));
lines.push('');

lines.push('### File-level changes');
lines.push(fence('text', nameStatus.join('\n')));
lines.push('');

lines.push('### Diff stat');
lines.push(fence('text', diffStat));
lines.push('');

lines.push('### Current dirty worktree (HEAD vs working tree)');
lines.push(fence('text', dirtyTracked.join('\n')));
lines.push('');

lines.push('### Untracked files');
lines.push(fence('text', untracked.map((l) => l.slice(2)).join('\n')));
lines.push('');

console.log(lines.join('\n'));
