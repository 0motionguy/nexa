/**
 * Quick smoke tests for handover-changes.mjs. Runs against the live
 * repo — checks the contract (output sections, error shape on bad ref)
 * rather than exact byte equality.
 *
 * Invoke with:
 *   node --test scripts/handover-changes.spec.mjs
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const script = resolve(here, 'handover-changes.mjs');

function run(args) {
  const res = spawnSync('node', [script, ...args], {
    cwd: resolve(here, '..'),
    encoding: 'utf8',
    shell: false,
  });
  return { code: res.status, stdout: res.stdout ?? '', stderr: res.stderr ?? '' };
}

test('exits with usage on missing args', () => {
  const r = run([]);
  assert.equal(r.code, 2);
  assert.match(r.stderr, /Usage:/);
});

test('exits with invalid-ref error on bad refs', () => {
  const r = run(['definitely-not-a-ref-zzz', 'HEAD']);
  assert.equal(r.code, 2);
  assert.match(r.stderr, /invalid ref/);
});

test('rejects shell-injection-style refs at validation', () => {
  // git rev-parse rejects refs with semicolons / spaces / metacharacters;
  // we never shell out so this can't execute even if validation were loose.
  const r = run(['; echo pwned', 'HEAD']);
  assert.equal(r.code, 2);
  assert.match(r.stderr, /invalid ref/);
});

test('produces inventory sections for HEAD~1..HEAD on clean ref range', () => {
  const r = run(['HEAD~1', 'HEAD']);
  // If the repo only has one commit this would fail; in NEXA we have many.
  if (r.code !== 0) {
    console.error('STDERR:', r.stderr);
  }
  assert.equal(r.code, 0);
  assert.match(r.stdout, /What changed:/);
  assert.match(r.stdout, /### Commits/);
  assert.match(r.stdout, /### File-level changes/);
  assert.match(r.stdout, /### Diff stat/);
  assert.match(r.stdout, /### Current dirty worktree/);
  assert.match(r.stdout, /### Untracked files/);
});

test('output includes auto-generated header marker', () => {
  const r = run(['HEAD~1', 'HEAD']);
  assert.equal(r.code, 0);
  assert.match(r.stdout, /Auto-generated by scripts\/handover-changes\.mjs/);
});
